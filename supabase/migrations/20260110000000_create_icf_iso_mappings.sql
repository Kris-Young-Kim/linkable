-- =============================================================================
-- ICF-ISO 매핑 테이블 생성 및 데이터 마이그레이션
-- =============================================================================
-- 목적: 하드코딩된 ICF-ISO 매핑을 DB로 이관하여 관리 용이성 향상
-- 참고: core/matching/iso-mapping.ts의 isoMappingTable 데이터 이관
-- 중요: ISO 코드는 반드시 Division 레벨(level 3, 6자리)이어야 함
-- =============================================================================

-- 1. icf_iso_mappings 테이블 생성
CREATE TABLE IF NOT EXISTS icf_iso_mappings (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- ICF 코드 (여러 개 가능)
  icf_codes TEXT[] NOT NULL,

  -- ISO 코드 (Division 레벨, 6자리)
  iso_code VARCHAR(10) NOT NULL,
  iso_code_id UUID REFERENCES iso_codes(id),

  -- 매핑 정보
  label VARCHAR(100) NOT NULL,
  description TEXT,
  base_score NUMERIC(3,2) DEFAULT 0.70,

  -- 메타데이터
  source VARCHAR(50) DEFAULT 'manual',
  confidence NUMERIC(3,2) DEFAULT 1.0,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- 인덱스
CREATE INDEX IF NOT EXISTS idx_icf_iso_mappings_icf ON icf_iso_mappings USING GIN(icf_codes);
CREATE INDEX IF NOT EXISTS idx_icf_iso_mappings_iso ON icf_iso_mappings(iso_code);
CREATE INDEX IF NOT EXISTS idx_icf_iso_mappings_active ON icf_iso_mappings(is_active) WHERE is_active = true;

-- 코멘트
COMMENT ON TABLE icf_iso_mappings IS 'ICF 코드와 ISO 9999 코드 간의 매핑 관계를 저장하는 테이블';
COMMENT ON COLUMN icf_iso_mappings.icf_codes IS 'ICF 코드 배열 (예: {d450, d465})';
COMMENT ON COLUMN icf_iso_mappings.iso_code IS 'ISO 9999 Division 코드 (6자리, 예: 12 06 03, 15 09 13)';
COMMENT ON COLUMN icf_iso_mappings.base_score IS '매칭 기본 점수 (0-1)';
COMMENT ON COLUMN icf_iso_mappings.source IS '매핑 출처 (manual, ai_inferred, research)';
COMMENT ON COLUMN icf_iso_mappings.confidence IS '매핑 신뢰도 (0-1)';

